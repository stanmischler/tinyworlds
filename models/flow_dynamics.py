import math
import torch
import torch.nn as nn
import torch.nn.functional as F
from models.positional_encoding import build_spatial_only_pe
from models.st_transformer import STTransformer


def timestep_embedding(t, dim):
    # sinusoidal embedding of a flow time t in [0, 1] (scaled by 1000 like DiT): [...] -> [..., dim]
    half = dim // 2
    freqs = torch.exp(-math.log(10000.0) * torch.arange(half, device=t.device, dtype=torch.float32) / half)  # [dim/2]
    args = t.float()[..., None] * 1000.0 * freqs  # [..., dim/2]
    return torch.cat([torch.cos(args), torch.sin(args)], dim=-1)  # [..., dim]


def shift_noise_level(s, shift):
    # timestep shift of Esser et al. (SD3) on the noise level s in [0, 1] (s = 1 pure noise): shift > 1 spends more
    # training steps / sampling steps at high noise; shift = 1 is the identity
    return shift * s / (1 + (shift - 1) * s)


class FlowDynamicsModel(nn.Module):
    """Flow-matching dynamics (STA-28): same causal ST-transformer as DynamicsModel, but the last frame's FSQ latents are
    generated by integrating a velocity field from Gaussian noise instead of MaskGIT unmasking.

    Path (rectified flow, t = 1 is data): x_t = t * x1 + (1 - t) * x0, x0 ~ N(0, I), velocity v = x1 - x0. Only the
    last frame is noised; the context frames are clean (their time embedding is t = 1). Each frame's FiLM conditioning
    is [action a_{t-1} (zeros at frame 0), embedding of its flow time], so the backbone's per-frame adaptive norms act as
    adaLN for the noise level. fm_pred 'v' regresses the velocity, 'x' predicts x1 and derives the velocity; the loss is
    the velocity MSE in both cases. Samples are rounded to the FSQ grid at the very end (unless round_latents is False, for
    the unit-RMS latents of a continuous tokenizer). fm_source "copy" (FlowC2S) and "bridge" (Brownian bridge) start the
    flow from the previous frame instead of noise."""

    def __init__(self, frame_size=(128, 128), patch_size=4, embed_dim=256, num_heads=8, hidden_dim=512, num_blocks=12,
                 latent_dim=6, num_bins=4, conditioning_dim=0, time_dim=64, fm_pred="v", fm_shift=1.0, qk_norm=True,
                 t_eps=0.05, round_latents=True, fm_source="noise", fm_source_noise=0.0, noise_cond=False, random_context=False,
                 bridge_loss="stabilised", bridge_t_max=0.999, bridge_delta=1e-4, correction=False, correction_weight=1.0,
                 token_loss="mse", token_loss_weight=1.0, topk_frac=0.05, focal_gamma=1.0, action_dropout_prob=0.0,
                 motion_loss_per_sample=False, dropout=0.0, action_token=False):
        super().__init__()
        # token_loss: how the per-token velocity error e [B, P] is reduced (see token_weighted_loss); "mse" = plain mean
        assert token_loss in ("mse", "motion", "topk", "focal"), token_loss
        assert token_loss == "mse" or fm_source != "bridge", 'token_loss needs fm_source "noise" or "copy"'
        self.token_loss, self.token_loss_weight = token_loss, float(token_loss_weight)
        self.topk_frac, self.focal_gamma = float(topk_frac), float(focal_gamma)
        # motion_loss_per_sample: the moving-token term is each sample's mean error over its moving tokens, averaged over
        # the samples that have any (False = pooled over the batch, so the samples with the most motion dominate)
        self.motion_loss_per_sample = bool(motion_loss_per_sample)
        # action dropout (training only): each action of the window is replaced by the learned null action with this
        # probability, independently; sampling with guidance_scale != 1 then mixes the velocities with and without the
        # last action (classifier-free guidance). The null action only exists when dropout is on (old checkpoints load).
        self.action_dropout_prob = float(action_dropout_prob)
        self.null_action = nn.Parameter(torch.zeros(1, 1, int(conditioning_dim or 0))) if action_dropout_prob > 0 else None
        self.guidance_scale = 1.0  # set by the eval; 1 = no guidance
        self.random_context = bool(random_context)  # train on the first Tc + 1 frames, Tc ~ U{1..T-1} per batch
        # fm_source (STA-61): "noise" = x0 ~ N(0, I) (original); "copy" = FlowC2S, x0 = the previous frame's latents
        # + fm_source_noise * N(0, I), so the flow carries frame t to frame t+1. noise_cond adds a second FiLM input, the
        # embedding of a per-frame noise level alpha (Bi-flow's denoising axis, see BiFlowDynamicsModel).
        # "bridge" = Brownian bridge from the clean previous frame (ViBT, arXiv 2511.23199), fm_source_noise = its scale s;
        # see bridge_point / bridge_loss. Bridge training times are uniform: fm_shift only shapes the sampling grid.
        assert fm_source in ("noise", "copy", "bridge"), fm_source
        self.fm_source, self.fm_source_noise, self.noise_cond = fm_source, float(fm_source_noise), bool(noise_cond)
        assert bridge_loss in ("stabilised", "plain"), bridge_loss
        self.bridge_objective, self.bridge_t_max, self.bridge_delta = bridge_loss, float(bridge_t_max), float(bridge_delta)
        self.round_latents = round_latents  # False for a continuous tokenizer (STA-62): samples are used as they are
        assert fm_pred in ("v", "x"), fm_pred
        self.fm_pred, self.fm_shift, self.t_eps = fm_pred, float(fm_shift), float(t_eps)
        self.num_bins, self.latent_dim = num_bins, latent_dim
        self.action_dim = int(conditioning_dim or 0)
        self.time_dim = time_dim
        H, W = frame_size

        self.latent_embed = nn.Linear(latent_dim, embed_dim)
        self.time_mlp = nn.Sequential(nn.Linear(time_dim, 2 * time_dim), nn.SiLU(), nn.Linear(2 * time_dim, time_dim))
        if self.noise_cond:
            self.alpha_mlp = nn.Sequential(nn.Linear(time_dim, 2 * time_dim), nn.SiLU(), nn.Linear(2 * time_dim, time_dim))
        self.transformer = STTransformer(
            embed_dim, num_heads, hidden_dim, num_blocks, causal=True,
            conditioning_dim=self.action_dim + time_dim * (2 if self.noise_cond else 1), qk_norm=qk_norm, dropout=dropout,
        )
        # action token: each frame's action a_{t-1} is also embedded as one extra token appended to that frame's P image
        # tokens, so they can attend to it in spatial attention; it goes through every block and is dropped before the
        # output head. FiLM still carries the action and the flow time. Zero-init: the token starts as the zero vector.
        self.action_token = bool(action_token)
        if self.action_token:
            assert self.action_dim > 0, 'action_token needs actions'
            self.action_token_embed = nn.Linear(self.action_dim, embed_dim)
            nn.init.zeros_(self.action_token_embed.weight); nn.init.zeros_(self.action_token_embed.bias)
        # zero-init output: the model starts by predicting v = 0 (or x1 = 0), as DiT's zero-init final layer
        self.output_mlp = nn.Linear(embed_dim, latent_dim)
        nn.init.zeros_(self.output_mlp.weight); nn.init.zeros_(self.output_mlp.bias)

        pe_spatial = build_spatial_only_pe((H, W), patch_size, embed_dim, device='cpu', dtype=torch.float32)  # [1,P,E]
        self.register_buffer("pos_spatial_dec", pe_spatial, persistent=False)

        # Correction training (Ahn et al., arXiv 2610.14136, "gated native" corrector of their Eq. 8): a second network C,
        # same architecture as the dynamics net D, reads the predicted clean frame x1_hat = x_t + s v (stop-gradient) in
        # the noisy frame's slot and outputs a velocity c; the corrected velocity is v' = v + gate * (c - v), gate [L]
        # starts at 0 so the corrected model starts as D. Trained jointly: loss = |v - u|^2 + correction_weight |v' - u|^2.
        # At sampling the correction is applied correction_k times per Euler step, on the first correction_interval
        # fraction of the steps, counted from the noisiest (inference knobs, set by the eval).
        self.correction, self.correction_weight = bool(correction), float(correction_weight)
        self.correction_k, self.correction_interval = 1, 1.0
        if self.correction:
            assert not self.action_token, 'correction does not support the action token'
            assert fm_pred == "v" and fm_source in ("noise", "copy") and not self.noise_cond, \
                'correction needs a velocity head and a straight path (fm_source noise or copy, no noise_cond)'
            self.corrector = nn.ModuleDict({name: copy.deepcopy(getattr(self, name)) for name in self.NET_MODULES})
            self.correction_gate = nn.Parameter(torch.zeros(latent_dim))  # [L]

    NET_MODULES = ("latent_embed", "time_mlp", "transformer", "output_mlp")  # the modules that make up one network

    def copy_dynamics_into_corrector(self):
        # corrector init (paper: C starts as a copy of the pretrained D); called after loading D's weights
        for name in self.NET_MODULES:
            self.corrector[name].load_state_dict(getattr(self, name).state_dict())

    def _conditioning(self, actions, t, T, alpha=None, time_mlp=None):
        # actions: [B, T-1, A] or None; t: [B, T] flow time per frame; alpha: [B, T] noise level (noise_cond only);
        # time_mlp: the corrector's (None = the dynamics net's) -> [B, T, A + Dt (+ Dt)]
        time_mlp = self.time_mlp if time_mlp is None else time_mlp
        temb = time_mlp(timestep_embedding(t, self.time_dim))  # [B, T, Dt]
        if self.noise_cond:
            alpha = torch.zeros_like(t) if alpha is None else alpha
            temb = torch.cat([temb, self.alpha_mlp(timestep_embedding(alpha, self.time_dim))], dim=-1)  # [B, T, 2Dt]
        if self.action_dim == 0:
            return temb
        a = self._frame_actions(actions, t.shape[0], T, t.device, temb.dtype)  # [B, T, A]
        return torch.cat([a, temb], dim=-1)  # [B, T, A + Dt]

    def _frame_actions(self, actions, B, T, device, dtype):
        # actions: [B, T-1, A] or None -> [B, T, A], a_{t-1} drives frame t (same shift as AdaptiveNormalizer does for
        # [B, T-1, A] conditioning); frame 0, or every frame without actions, gets zeros
        if actions is None:
            return torch.zeros(B, T, self.action_dim, device=device, dtype=dtype)
        return torch.cat([torch.zeros_like(actions[:, :1]), actions[:, :T - 1]], dim=1).to(dtype)

    def net(self, latents, actions, t, alpha=None, modules=None):
        # latents: [B, T, P, L] (last frame noisy); actions: [B, T-1, A] or None; t, alpha: [B, T]; modules: the corrector
        # (None = the dynamics net) -> raw output [B, T, P, L]
        m = self if modules is None else modules
        B, T, P, L = latents.shape
        emb = m.latent_embed(latents.float()) + self.pos_spatial_dec.to(latents.device)  # [B, T, P, E]
        if self.action_token:
            a = self._frame_actions(actions, B, T, latents.device, emb.dtype)  # [B, T, A]
            emb = torch.cat([emb, self.action_token_embed(a)[:, :, None]], dim=2)  # [B, T, P+1, E] token appended last
        out = m.transformer(emb, conditioning=self._conditioning(actions, t, T, alpha, m.time_mlp))  # [B, T, P(+1), E]
        return m.output_mlp(out[:, :, :P])  # [B, T, P, L] action token dropped

    def velocity(self, latents, actions, t):
        # velocity of the last frame: [B, P, L]
        out = self.net(latents, actions, t)[:, -1]  # [B, P, L]
        if self.fm_pred == "v":
            return out
        s = (1 - t[:, -1]).clamp_min(self.t_eps)[:, None, None]  # [B, 1, 1] noise level of the target
        return (out.float() - latents[:, -1].float()) / s  # (x1_hat - x_t) / (1 - t)

    def drop_actions(self, actions):
        # actions: [B, T-1, A] -> same, each action replaced by the null action with prob. action_dropout_prob
        drop = torch.rand(actions.shape[:2], device=actions.device) < self.action_dropout_prob  # [B, T-1]
        return torch.where(drop[..., None], self.null_action.to(actions.dtype), actions)  # [B, T-1, A]

    def token_weighted_loss(self, v_hat, v, token_mask=None, loss_mask=None):
        # v_hat, v: [B, P, L] predicted and true velocity; token_mask: [B, P] moving tokens (token_loss "motion");
        # loss_mask: [B, P] tokens in the loss (None = all), e.g. without the border revealed by a token shift
        e = ((v_hat.float() - v) ** 2).mean(-1)  # [B, P] per-token velocity error
        valid = torch.ones_like(e) if loss_mask is None else loss_mask.float()  # [B, P]
        mse = (valid * e).sum() / valid.sum().clamp_min(1)  # mean error over the valid tokens (= e.mean() if all valid)
        if self.token_loss == "motion":
            if token_mask is None:  # e.g. the test curve: no frames to build the mask from
                return mse
            m = token_mask.float() * valid  # [B, P]
            if self.motion_loss_per_sample:
                # each sample's mean error over its moving tokens, averaged over the samples that have motion
                n = m.sum(1)  # [B] moving tokens per sample
                per_sample = (m * e).sum(1) / n.clamp_min(1)  # [B]
                has_motion = (n > 0).float()  # [B]
                return mse + self.token_loss_weight * (has_motion * per_sample).sum() / has_motion.sum().clamp_min(1)
            # extra term normalised by the moving area (as CGSReg, arXiv 2607.15142): mean error over the batch's moving tokens
            return mse + self.token_loss_weight * (m * e).sum() / m.sum().clamp_min(1)
        if self.token_loss == "topk":
            # mean error of each sample's worst topk_frac valid tokens
            k = max(1, round(self.topk_frac * e.shape[1]))
            return mse + self.token_loss_weight * (valid * e).topk(k, dim=1).values.mean()
        if self.token_loss == "focal":
            # dynamic focal weight w = sg((e / e_mean)^gamma), e_mean = the sample's mean error over its valid tokens:
            # tokens above it weigh more; the loss is the mean of w * e over the valid tokens
            e_mean = (valid * e).sum(1, keepdim=True) / valid.sum(1, keepdim=True).clamp_min(1)  # [B, 1]
            w = (e / e_mean.clamp_min(1e-8)).pow(self.focal_gamma).detach()  # [B, P]
            return (valid * w * e).sum() / valid.sum().clamp_min(1)
        return mse

    def corrected_velocity(self, context, xt, v, actions, t):
        # one correction: context [B, Tc, P, L] clean frames; xt [B, P, L] the noisy last frame; v [B, P, L] its current
        # velocity; t [B, Tc+1] flow times (last = the noisy frame's) -> v' [B, P, L]. v enters detached (full stop-grad)
        v = v.detach().float()
        s = (1 - t[:, -1])[:, None, None]  # [B, 1, 1] noise level
        x1_hat = xt + s * v  # [B, P, L] predicted clean frame
        inp = torch.cat([context.float(), x1_hat[:, None]], dim=1)  # [B, Tc+1, P, L] x1_hat replaces x_t (not added)
        c = self.net(inp, actions, t, modules=self.corrector)[:, -1].float()  # [B, P, L]
        return v + self.correction_gate * (c - v)  # [B, P, L]

    def forward(self, latents, training=True, conditioning=None, targets=None, token_mask=None, loss_mask=None):
        # latents: [B, T, P, L] clean FSQ (or continuous) latents; conditioning: [B, T-1, A] actions. Returns
        # (v_hat, (x1_hat, s, parts), loss) like DynamicsModel.forward returns (logits, mask, loss); x1_hat = x_t + s * v_hat [B, P, L]
        # is the predicted clean last frame, s [B] its noise level and parts the loss terms to log ({} without correction).
        # token_mask: [B, P] moving tokens (token_loss "motion"); loss_mask: [B, P] tokens in the loss (None = all).
        if self.null_action is not None and self.training and conditioning is not None:
            conditioning = self.drop_actions(conditioning)
        if self.random_context and training and latents.shape[1] > 2:
            Tc = int(torch.randint(1, latents.shape[1], ()))  # context frames, 1 .. T-1 (one draw per batch: static shapes per Tc)
            latents = latents[:, :Tc + 1]  # [B, Tc+1, P, L]
            conditioning = None if conditioning is None else conditioning[:, :Tc]  # [B, Tc, A]
        if self.fm_source == "bridge":
            return self.bridge_forward(latents, conditioning)
        B, T, P, L = latents.shape
        x1 = latents[:, -1].float()  # [B, P, L]
        x0 = self.source(latents[:, -2]) if self.fm_source == "copy" else torch.randn_like(x1)  # [B, P, L]
        s = shift_noise_level(torch.rand(B, device=latents.device), self.fm_shift)  # [B] noise level
        tt = 1 - s  # [B] flow time
        xt = tt[:, None, None] * x1 + s[:, None, None] * x0  # [B, P, L]
        noisy = torch.cat([latents[:, :-1].float(), xt[:, None]], dim=1)  # [B, T, P, L]
        t = torch.ones(B, T, device=latents.device)  # [B, T] context is clean (t = 1)
        t[:, -1] = tt
        v_hat = self.velocity(noisy, conditioning, t)  # [B, P, L]
        loss = self.token_weighted_loss(v_hat, x1 - x0, token_mask, loss_mask)
        x1_hat = xt + s[:, None, None] * v_hat.float()  # [B, P, L] predicted clean latents (for the frequency loss)
        parts = {}  # loss terms to log
        if self.correction:
            v_corr = self.corrected_velocity(latents[:, :-1], xt, v_hat, conditioning, t)  # [B, P, L]
            corr_loss = F.mse_loss(v_corr, x1 - x0)
            parts = {'flow_loss': loss.detach(), 'corr_loss': corr_loss.detach()}
            loss = loss + self.correction_weight * corr_loss
        return v_hat, (x1_hat, s, parts), loss

    def bridge_point(self, z0, z1):
        # Brownian bridge between the clean previous frame z0 and the next frame z1 ([B, P, L] each), ViBT Eq. 7-8:
        # x_t = (1 - t) z0 + t z1 + s sqrt(t (1 - t)) eps,  target u_t = (z1 - x_t) / (1 - t) = (z1 - z0) - s sqrt(t / (1 - t)) eps
        B = z0.shape[0]
        t = torch.rand(B, device=z0.device) * self.bridge_t_max  # [B] t ~ U(0, t_max): u_t diverges at t = 1
        tb = t[:, None, None]  # [B, 1, 1]
        eps = torch.randn_like(z1)  # [B, P, L]
        s = self.fm_source_noise
        xt = (1 - tb) * z0 + tb * z1 + s * torch.sqrt(tb * (1 - tb)) * eps  # [B, P, L]
        u = (z1 - z0) - s * torch.sqrt(tb / (1 - tb)) * eps  # [B, P, L]
        return t, xt, u

    def bridge_loss(self, v_hat, u, z0, z1, t):
        # velocity MSE per sample, divided by alpha^2 = E||u_t||^2 / ||z1 - z0||^2 (ViBT Eq. 14-15, "stabilised") so, within
        # a sample, every t weighs the same (across the batch a sample then weighs in proportion to its motion); written with means over the P*L latent values: alpha^2 = 1 + s^2 t / ((1 - t) mean((z1 - z0)^2)).
        # bridge_delta keeps alpha finite on static frame pairs (z1 = z0).
        err = ((v_hat.float() - u) ** 2).mean(dim=(1, 2))  # [B]
        if self.bridge_objective == "plain":
            return err.mean()
        motion = ((z1 - z0) ** 2).mean(dim=(1, 2)) + self.bridge_delta  # [B]
        alpha2 = 1 + self.fm_source_noise ** 2 * t / ((1 - t) * motion)  # [B]
        return (err / alpha2).mean()

    def bridge_forward(self, latents, conditioning):
        # latents: [B, T, P, L] clean; conditioning: [B, T-1, A] -> (v_hat, None, loss)
        B, T = latents.shape[:2]
        z0, z1 = latents[:, -2].float(), latents[:, -1].float()  # [B, P, L]
        tt, xt, u = self.bridge_point(z0, z1)
        noisy = torch.cat([latents[:, :-1].float(), xt[:, None]], dim=1)  # [B, T, P, L]
        t = torch.ones(B, T, device=latents.device)  # [B, T] context is clean (t = 1)
        t[:, -1] = tt
        v_hat = self.velocity(noisy, conditioning, t)  # [B, P, L]
        return v_hat, None, self.bridge_loss(v_hat, u, z0, z1, tt)

    def source(self, prev, generator=None):
        # FlowC2S source: previous frame's latents [B, P, L] + fm_source_noise * N(0, I)
        prev = prev.float()
        if self.fm_source_noise == 0:
            return prev
        # randn_like when unseeded: torch.randn(shape) fails under torch.compile(dynamic=True) (symbolic shape)
        n = torch.randn_like(prev) if generator is None else torch.randn(prev.shape, device=prev.device, generator=generator)
        return prev + self.fm_source_noise * n

    def bridge_noise(self, x, s_k, s_next, generator=None):
        # variance-corrected Euler-Maruyama noise (ViBT Eq. 17): s sqrt(dt (1 - t_{k+1}) / (1 - t_k)) eps, with 1 - t = the
        # grid's noise level s_grid; zero on the last step (t_{k+1} = 1). x: [B, P, L] -> [B, P, L]
        dt = s_k - s_next
        eta = self.fm_source_noise * torch.sqrt(dt * s_next / s_k)
        n = torch.randn_like(x) if generator is None else torch.randn(x.shape, device=x.device, generator=generator)
        return eta * n

    def round_to_grid(self, x):
        # continuous latents -> nearest FSQ grid value in [-1, 1] (same grid as FiniteScalarQuantizer)
        digits = torch.round((x + 1) * 0.5 * (self.num_bins - 1)).clamp(0, self.num_bins - 1)
        return 2 * digits / (self.num_bins - 1) - 1

    def guided_velocity(self, inp, conditioning, t):
        # inp: [B, Tc+1, P, L]; conditioning: [B, Tc, A] or None -> velocity [B, P, L], guided on the last action:
        # v = v(null last action) + w * (v(a) - v(null last action)), w = guidance_scale (w = 1: plain v(a))
        v = self.velocity(inp, conditioning, t).float()  # [B, P, L]
        if self.guidance_scale == 1 or conditioning is None:
            return v
        assert self.null_action is not None, 'guidance needs a model trained with action_dropout_prob > 0'
        null_last = torch.cat([conditioning[:, :-1], self.null_action.to(conditioning.dtype).expand(len(conditioning), 1, -1)], 1)
        v_null = self.velocity(inp, null_last, t).float()  # [B, P, L]
        return v_null + self.guidance_scale * (v - v_null)

    @torch.no_grad()
    def sample_next(self, context_latents, conditioning, num_steps, generator=None):
        # context_latents: [B, Tc, P, L]; conditioning: [B, Tc, A] (last = transition into the new frame) or None
        # Euler integration from noise over the shifted grid; returns the rounded new frame [B, P, L]
        B, Tc, P, L = context_latents.shape
        dev = context_latents.device
        if self.fm_source == "copy":
            x = self.source(context_latents[:, -1], generator)  # [B, P, L] FlowC2S: start from the last context frame
        elif self.fm_source == "bridge":
            x = context_latents[:, -1].float()  # [B, P, L] bridge: start from the clean last context frame
        else:
            x = torch.randn(B, P, L, device=dev, generator=generator)  # [B, P, L]
        s_grid = shift_noise_level(torch.linspace(1, 0, num_steps + 1, device=dev), self.fm_shift)  # [N+1], 1 -> 0
        t = torch.ones(B, Tc + 1, device=dev)  # [B, Tc+1]
        for k in range(num_steps):
            t[:, -1] = 1 - s_grid[k]
            inp = torch.cat([context_latents.float(), x[:, None]], dim=1)  # [B, Tc+1, P, L]
            v = self.guided_velocity(inp, conditioning, t)  # [B, P, L]
            if self.correction and k < math.ceil(self.correction_interval * num_steps):  # the first, noisiest steps
                for _ in range(self.correction_k):
                    v = self.corrected_velocity(context_latents, x, v, conditioning, t)
            x = x + (s_grid[k] - s_grid[k + 1]) * v  # dt = t_{k+1} - t_k
            if self.fm_source == "bridge":
                x = x + self.bridge_noise(x, s_grid[k], s_grid[k + 1], generator)
        return self.round_to_grid(x) if self.round_latents else x

    def sample_next_with_grad(self, context_latents, conditioning, num_steps, grad_steps):
        # differentiable version of sample_next for the sampled-frame loss (noise source, no guidance, no correction):
        # the same Euler steps from noise, where only the last grad_steps keep their graph (DRaFT-K, arXiv 2309.17400).
        # Each of those steps reads its input detached (DRTune, arXiv 2405.00760): x_N = x_start + sum_k dt_k * v(sg(x_k)),
        # so the gradient reaches the weights through each kept velocity, not through the chain of steps.
        # context_latents: [B, Tc, P, L] clean; conditioning: [B, Tc, A] or None -> new frame [B, P, L] (not rounded)
        assert self.fm_source == "noise" and not self.correction and self.guidance_scale == 1 and not self.round_latents, \
            'sample_next_with_grad: noise source, continuous latents, no correction or guidance'
        B, Tc, P, L = context_latents.shape
        dev = context_latents.device
        x = torch.randn(B, P, L, device=dev)  # [B, P, L]
        s_grid = shift_noise_level(torch.linspace(1, 0, num_steps + 1, device=dev), self.fm_shift)  # [N+1], 1 -> 0
        for k in range(num_steps):
            with torch.set_grad_enabled(k >= num_steps - grad_steps):
                t = torch.ones(B, Tc + 1, device=dev)  # [B, Tc+1] fresh each step (no in-place edit of a graph input)
                t[:, -1] = 1 - s_grid[k]
                inp = torch.cat([context_latents.float(), x.detach()[:, None]], dim=1)  # [B, Tc+1, P, L]
                v = self.velocity(inp, conditioning, t).float()  # [B, P, L]
                x = x + (s_grid[k] - s_grid[k + 1]) * v
        return x

    def clean_guess_with_grad(self, context_latents, conditioning, num_steps):
        # the sampled-frame loss scored at a random step of the sampler instead of its end: k Euler steps from noise
        # without gradient (k uniform in 0..num_steps-1, one k for the batch), then the model's one-shot guess of the
        # clean frame there, x1_hat = x_k + s_k * v(sg(x_k)) as in forward(). The gradient reaches the weights through
        # that velocity, at every noise level of the eval's grid, including the early ones that fix the layout.
        # context_latents: [B, Tc, P, L] clean; conditioning: [B, Tc, A] or None -> clean-frame guess [B, P, L]
        assert self.fm_source == "noise" and not self.correction and self.guidance_scale == 1 and not self.round_latents, \
            'clean_guess_with_grad: noise source, continuous latents, no correction or guidance'
        B, Tc, P, L = context_latents.shape
        dev = context_latents.device
        s_grid = shift_noise_level(torch.linspace(1, 0, num_steps + 1, device=dev), self.fm_shift)  # [N+1], 1 -> 0
        k = int(torch.randint(num_steps, ()))  # Euler steps taken before the guess
        x = torch.randn(B, P, L, device=dev)  # [B, P, L]
        for j in range(k + 1):
            with torch.set_grad_enabled(j == k):
                t = torch.ones(B, Tc + 1, device=dev)  # [B, Tc+1]
                t[:, -1] = 1 - s_grid[j]
                inp = torch.cat([context_latents.float(), x.detach()[:, None]], dim=1)  # [B, Tc+1, P, L]
                v = self.velocity(inp, conditioning, t).float()  # [B, P, L]
                if j < k:
                    x = x + (s_grid[j] - s_grid[j + 1]) * v
        return x.detach() + s_grid[k] * v

    @torch.no_grad()
    def forward_inference(self, context_latents, prediction_horizon, num_steps, index_to_latents_fn=None,
                          conditioning=None, schedule_k=None, temperature=None, generator=None):
        # same interface as DynamicsModel.forward_inference (num_steps = Euler steps; schedule_k / temperature unused)
        # context_latents: [B, T_ctx, P, L]; conditioning: [B, >= T_ctx+H-1, A] -> [B, T_ctx + H, P, L]
        latents = context_latents
        for h in range(int(prediction_horizon)):
            Tc = latents.shape[1]
            cond = None if conditioning is None else conditioning[:, :Tc]  # [B, Tc, A]
            new = self.sample_next(latents, cond, num_steps, generator=generator)  # [B, P, L]
            latents = torch.cat([latents, new[:, None].to(latents.dtype)], dim=1)
        return latents

    @property
    def model_type(self) -> str:
        return ModelType.FlowDynamicsModel


class BiFlowDynamicsModel(nn.Module):
    """Video Bi-flow (Liu & Ritschel, ICCV 2025, arXiv 2503.06364), adapted to action-conditioned next-frame latents
    (STA-61). The flow carries the previous frame z0 to the next frame z1 along a noised straight line (Eq. 4):
    x_{t,alpha} = z0 + t (z1 - z0) + alpha n, t ~ U(0, 1), alpha ~ U(0, alpha_max), n ~ N(0, I). Two separate networks
    (as the paper, Supp. A) share the FlowDynamicsModel backbone: `vel` regresses the velocity z1 - z0 and `den` the noise
    n (Eq. 5); both see the clean context frames and are FiLM-conditioned on [action, emb(t), emb(alpha)].
    Sampling (Eq. 8-9) starts at z_prev + eps n and walks the line (t, alpha): (0, eps) -> (1, 0),
    dx/dk = v - eps * n_hat. eps (bf_eps) is an inference knob."""

    def __init__(self, bf_alpha_max=1.0, bf_eps=0.1, **flow_kwargs):
        super().__init__()
        self.bf_alpha_max, self.bf_eps = float(bf_alpha_max), float(bf_eps)
        flow_kwargs.update(fm_pred="v", fm_shift=1.0, fm_source="copy", fm_source_noise=0.0, noise_cond=True)
        self.vel = FlowDynamicsModel(**flow_kwargs)
        self.den = FlowDynamicsModel(**flow_kwargs)
        self.round_latents = self.vel.round_latents

    def _fields(self, ctx, x, conditioning, tt, alpha):
        # ctx: [B, Tc, P, L] clean; x: [B, P, L] current point; tt, alpha: [B] -> velocity and noise [B, P, L] each
        B, Tc = ctx.shape[:2]
        inp = torch.cat([ctx.float(), x[:, None].float()], dim=1)  # [B, Tc+1, P, L]
        t = torch.ones(B, Tc + 1, device=x.device)  # [B, Tc+1] context frames are clean data (t = 1, alpha = 0)
        t[:, -1] = tt
        a = torch.zeros(B, Tc + 1, device=x.device)  # [B, Tc+1]
        a[:, -1] = alpha
        v = self.vel.net(inp, conditioning, t, a)[:, -1]  # [B, P, L]
        n = self.den.net(inp, conditioning, t, a)[:, -1]  # [B, P, L]
        return v, n

    def forward(self, latents, training=True, conditioning=None, targets=None):
        # latents: [B, T, P, L] clean; conditioning: [B, T-1, A] -> (v_hat, None, loss) like FlowDynamicsModel
        B = latents.shape[0]
        z0, z1 = latents[:, -2].float(), latents[:, -1].float()  # [B, P, L]
        t = torch.rand(B, device=latents.device)  # [B]
        alpha = torch.rand(B, device=latents.device) * self.bf_alpha_max  # [B]
        n = torch.randn_like(z1)  # [B, P, L]
        x = z0 + t[:, None, None] * (z1 - z0) + alpha[:, None, None] * n  # [B, P, L]
        v_hat, n_hat = self._fields(latents[:, :-1], x, conditioning, t, alpha)
        loss = F.mse_loss(v_hat.float(), z1 - z0) + F.mse_loss(n_hat.float(), n)
        return v_hat, None, loss

    @torch.no_grad()
    def sample_next(self, context_latents, conditioning, num_steps, generator=None):
        # context_latents: [B, Tc, P, L]; conditioning: [B, Tc, A] or None -> new frame [B, P, L] (Euler, Eq. 8-9)
        eps = self.bf_eps
        z = context_latents[:, -1].float()  # [B, P, L]
        x = z + eps * torch.randn(z.shape, device=z.device, generator=generator) if eps > 0 else z
        B = z.shape[0]
        ks = torch.linspace(0, 1, num_steps + 1, device=z.device)  # [N+1]
        for i in range(num_steps):
            k = ks[i]
            v, n = self._fields(context_latents, x, conditioning, k.expand(B), (eps * (1 - k)).expand(B))
            x = x + (ks[i + 1] - k) * (v.float() - eps * n.float())
        return self.vel.round_to_grid(x) if self.round_latents else x

    forward_inference = FlowDynamicsModel.forward_inference

    @property
    def model_type(self) -> str:
        return ModelType.FlowDynamicsModel


class EDMDynamicsModel(FlowDynamicsModel):
    """EDM diffusion dynamics (Karras et al. 2022, as DIAMOND's pixel world model, arXiv 2405.12399): same causal
    ST-transformer as FlowDynamicsModel (`net`), but the last frame is noised as x_sigma = x + sigma * eps and the network
    output F is preconditioned into a denoiser D(x_sigma) = c_skip x_sigma + c_out F(c_in x_sigma, c_noise), with
    c_in = 1 / sqrt(sigma^2 + sd^2), c_skip = sd^2 / (sigma^2 + sd^2), c_out = sigma sd / sqrt(sigma^2 + sd^2),
    c_noise = log(sigma) / 4 (sd = sigma_data). Training: log sigma ~ N(p_mean, p_std^2), loss = MSE(F, (x - c_skip x_sigma) / c_out),
    which is EDM's lambda(sigma)-weighted denoiser loss. The clean context frames are treated as noised at sigma_min
    (input scaled by c_in(sigma_min), c_noise(sigma_min) as their time input). Sampling: Euler on the Karras grid
    sigma_max -> sigma_min (rho), then 0; 1 step returns D(sigma_max noise), the conditional mean. Only the backbone is
    inherited: the fm_* / correction / guidance options of FlowDynamicsModel are unused (train_dynamics.py asserts them off)."""

    def __init__(self, edm_p_mean=-0.4, edm_p_std=1.2, edm_sigma_data=0.5, edm_sigma_min=0.002, edm_sigma_max=5.0,
                 edm_rho=7.0, **flow_kwargs):
        super().__init__(**flow_kwargs)
        self.p_mean, self.p_std, self.sigma_data = float(edm_p_mean), float(edm_p_std), float(edm_sigma_data)
        self.sigma_min, self.sigma_max, self.rho = float(edm_sigma_min), float(edm_sigma_max), float(edm_rho)

    def preconditioning(self, sigma):
        # sigma: [B] -> c_in, c_skip, c_out, c_noise, each [B]
        sd2 = self.sigma_data ** 2
        c_in = 1 / torch.sqrt(sigma ** 2 + sd2)
        c_skip = sd2 / (sigma ** 2 + sd2)
        c_out = sigma * self.sigma_data / torch.sqrt(sigma ** 2 + sd2)
        c_noise = torch.log(sigma) / 4
        return c_in, c_skip, c_out, c_noise

    def denoise(self, context, x_noisy, sigma, conditioning):
        # context: [B, Tc, P, L] clean frames; x_noisy: [B, P, L]; sigma: [B] -> (D [B, P, L] denoised frame, F [B, P, L] raw output)
        B, Tc = context.shape[:2]
        c_in, c_skip, c_out, c_noise = self.preconditioning(sigma)
        ctx_sigma = torch.full_like(sigma, self.sigma_min)  # [B] the context's nominal noise level
        ctx_in, _, _, ctx_noise = self.preconditioning(ctx_sigma)
        inp = torch.cat([ctx_in[:, None, None, None] * context.float(), (c_in[:, None, None] * x_noisy)[:, None]], dim=1)  # [B, Tc+1, P, L]
        t = torch.cat([ctx_noise[:, None].expand(B, Tc), c_noise[:, None]], dim=1)  # [B, Tc+1] time input per frame
        F_out = self.net(inp, conditioning, t)[:, -1].float()  # [B, P, L]
        D = c_skip[:, None, None] * x_noisy + c_out[:, None, None] * F_out  # [B, P, L]
        return D, F_out

    def forward(self, latents, training=True, conditioning=None, targets=None, token_mask=None):
        # latents: [B, T, P, L] clean; conditioning: [B, T-1, A] -> (D, (D, sigma, {}), loss) like FlowDynamicsModel.forward
        x = latents[:, -1].float()  # [B, P, L]
        sigma = torch.exp(self.p_mean + self.p_std * torch.randn_like(x[:, 0, 0]))  # [B]
        x_noisy = x + sigma[:, None, None] * torch.randn_like(x)  # [B, P, L]
        D, F_out = self.denoise(latents[:, :-1], x_noisy, sigma, conditioning)
        _, c_skip, c_out, _ = self.preconditioning(sigma)
        F_target = (x - c_skip[:, None, None] * x_noisy) / c_out[:, None, None]  # [B, P, L]
        loss = F.mse_loss(F_out, F_target)
        return D, (D, sigma, {}), loss

    def karras_sigmas(self, num_steps, device):
        # [N + 1]: sigma_max -> sigma_min on the rho grid, then 0 (N = 1: [sigma_max, 0])
        ramp = torch.linspace(0, 1, num_steps, device=device) if num_steps > 1 else torch.zeros(1, device=device)
        lo, hi = self.sigma_min ** (1 / self.rho), self.sigma_max ** (1 / self.rho)
        sigmas = (hi + ramp * (lo - hi)) ** self.rho  # [N]
        return torch.cat([sigmas, torch.zeros(1, device=device)])

    @torch.no_grad()
    def sample_next(self, context_latents, conditioning, num_steps, generator=None):
        # context_latents: [B, Tc, P, L]; conditioning: [B, Tc, A] or None -> new frame [B, P, L] (Euler on the Karras grid)
        B, Tc, P, L = context_latents.shape
        dev = context_latents.device
        sigmas = self.karras_sigmas(num_steps, dev)  # [N+1]
        x = sigmas[0] * torch.randn(B, P, L, device=dev, generator=generator)  # [B, P, L]
        for k in range(num_steps):
            D, _ = self.denoise(context_latents, x, sigmas[k].expand(B), conditioning)
            d = (x - D) / sigmas[k]  # [B, P, L] dx/dsigma
            x = x + (sigmas[k + 1] - sigmas[k]) * d  # the last step (sigma -> 0) lands on D
        return x


class RegressionDynamicsModel(FlowDynamicsModel):
    """One-pass regression dynamics, the non-generative baseline for FlowDynamicsModel: same causal ST-transformer (`net`),
    action token and FiLM, but no noise, no flow time and no sampling loop. The new frame's slot holds zeros (direct
    regression) or a copy of the last context frame (residual: the output is added to it), and the prediction is trained
    by MSE against the true next latents. Every frame's flow time is fixed at t = 1, so the FiLM time embedding is a
    constant and only the action varies. The fm_* / correction / guidance / token_loss options of FlowDynamicsModel are
    unused (train_dynamics.py asserts them off)."""

    def __init__(self, regression_residual=False, **flow_kwargs):
        super().__init__(**flow_kwargs)
        self.residual = bool(regression_residual)

    def predict(self, context, conditioning):
        # context: [B, Tc, P, L] clean frames; conditioning: [B, Tc, A] or None -> predicted next latents [B, P, L]
        B, Tc = context.shape[:2]
        prev = context[:, -1].float()  # [B, P, L]
        slot = prev if self.residual else torch.zeros_like(prev)  # [B, P, L] input in the new frame's slot
        inp = torch.cat([context.float(), slot[:, None]], dim=1)  # [B, Tc+1, P, L]
        t = torch.ones(B, Tc + 1, device=context.device)  # [B, Tc+1] constant time input
        out = self.net(inp, conditioning, t)[:, -1].float()  # [B, P, L]
        return prev + out if self.residual else out

    def forward(self, latents, training=True, conditioning=None, targets=None, token_mask=None, loss_mask=None):
        # latents: [B, T, P, L] clean; conditioning: [B, T-1, A]; loss_mask: [B, P] tokens in the loss (None = all)
        # -> (x1_hat, (x1_hat, s, {}), loss) like FlowDynamicsModel.forward, s = 0 (no noise)
        x1 = latents[:, -1].float()  # [B, P, L]
        x1_hat = self.predict(latents[:, :-1], conditioning)  # [B, P, L]
        loss = self.token_weighted_loss(x1_hat, x1, loss_mask=loss_mask)  # masked MSE over the latents
        return x1_hat, (x1_hat, torch.zeros_like(x1[:, 0, 0]), {}), loss

    @torch.no_grad()
    def sample_next(self, context_latents, conditioning, num_steps, generator=None):
        # context_latents: [B, Tc, P, L]; conditioning: [B, Tc, A] or None -> new frame [B, P, L]; one pass, num_steps unused
        return self.predict(context_latents, conditioning)
